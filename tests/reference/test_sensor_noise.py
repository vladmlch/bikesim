"""NumPy oracle draws are independent of the shared implementation under test."""
from dataclasses import replace
import numpy as np
import pytest
from bike_sim.sim.research.sensor_noise import NoiseTape, SensorNoiseSource, build_noise_tape
from bike_sim.sim.research.sensors import SensorConfig, SensorPipeline


def legacy_draws(config, seed, count):
    noise_seed, dropout_seed = np.random.SeedSequence(seed).spawn(2)
    noise_rng = np.random.default_rng(noise_seed)
    dropout_rng = np.random.default_rng(dropout_seed)
    rows, uniforms = [], []
    for _ in range(count):
        acceleration = noise_rng.normal(0., config.acceleration_std_mps2, 3)
        gyro = noise_rng.normal(0., config.gyro_std_rad_s)
        encoder = noise_rng.normal(0., config.encoder_std_rad_s, 3)
        torque = noise_rng.normal(0., config.torque_std_nm, 2)
        rows.append([*acceleration, gyro, *encoder, *torque])
        uniforms.append(dropout_rng.random())
    return np.asarray(rows), np.asarray(uniforms)


@pytest.mark.parametrize('seed', [0, 19, 2**63+11])
@pytest.mark.parametrize('config', [SensorConfig(), SensorConfig.ideal(),
    replace(SensorConfig(), acceleration_std_mps2=0., gyro_std_rad_s=0., imu_enabled=False)])
def test_exact_legacy_call_order(config, seed):
    tape = build_noise_tape(config, seed=seed, count=128)
    noise, uniform = legacy_draws(config, seed, 128)
    np.testing.assert_array_equal(tape.noise, noise)
    np.testing.assert_array_equal(tape.dropout_uniform, uniform)


def test_zero_scales_and_imu_switch_do_not_shift_other_channels():
    base = SensorConfig()
    reference = build_noise_tape(base, seed=31, count=64)
    masked = build_noise_tape(replace(base, imu_enabled=False,
        acceleration_std_mps2=0., gyro_std_rad_s=0.), seed=31, count=64)
    np.testing.assert_array_equal(reference.noise[:, 4:], masked.noise[:, 4:])
    np.testing.assert_array_equal(reference.dropout_uniform, masked.dropout_uniform)


def test_draws_own_configuration_and_tape_owns_buffers():
    config = SensorConfig()
    source = SensorNoiseSource(config, seed=0)
    assert source.config is not config
    noise, dropout = np.ones((2, 9)), np.full(2, .25)
    tape = NoiseTape(noise, dropout)
    noise.fill(99.)
    dropout.fill(.99)
    np.testing.assert_array_equal(tape.noise, np.ones((2, 9)))
    np.testing.assert_array_equal(tape.dropout_uniform, [.25, .25])
    assert not tape.noise.flags.writeable
    assert not tape.dropout_uniform.flags.writeable
    with pytest.raises(ValueError):
        tape.noise[0, 0] = 0.


