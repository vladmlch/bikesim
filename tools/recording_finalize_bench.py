"""Time the recording finalization seam: encode -> Arrow -> DuckDB write.

Runs a real native ride episode (``create_native_ride`` over the same
settled t=0 sim ``tests/reference/_native_runtime_support.make_python_ride``
builds), seals it, then measures the three bounded publication stages of
``storage._streams``/``_write_batch`` separately:

* ``source.tables(batch_rows=...)`` — the catalog projection: the C++
  ``encode_table`` projector by default, or the reviewed
  ``encode_rows``/canonical path under ``--oracle`` (which pins
  ``native_encode.compile_plan`` to ``None`` so every spec falls back);
* RecordBatch assembly — ``pieces_to_arrow`` for ``PieceBatch`` fragments,
  ``arrow_batch`` for ``TableBatch`` (``commands_applied`` is a
  ``TableBatch`` in both modes);
* the DuckDB ingestion — ``create_streams`` plus, per batch, the
  register/INSERT ... SELECT/unregister sequence ``_write_batch`` runs,
  inside one transaction with CHECKPOINT, into ``tempfile.mkdtemp``.

Production interleaves the stages per batch; separating them attributes
cost at the price of holding assembled RecordBatches in memory — fine at
the default episode size. The per-table encode breakdown attributes each
``next()`` of the stream to the batch it yields: on the oracle path the
first batch of each window also absorbs that window's shared canonical
materialization (in practice ``commands_applied``/``physics``); the rest
of a window's cost lands on the table whose ``encode_rows`` ran it.
The default native dispatch itself — every physical stream through
``encode_table``, ``encode_rows`` never invoked — is pinned by
``tests/reference/test_native_encode_columns.py::test_whole_episode_single_pass``.

    BIKE_NATIVE_BUILD_PATH="$PWD/native/build" \
        uv run --frozen --group native python tools/recording_finalize_bench.py
    BIKE_NATIVE_BUILD_PATH="$PWD/native/build" \
        uv run --frozen --group native python tools/recording_finalize_bench.py --oracle
"""
import argparse
import json
from pathlib import Path
import sys
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'src'))

PHYSICS = ROOT/'examples/research/viewer_physics_welded.toml'
TRACK = ROOT/'examples/research/rough_uphill_savage.toml'
# The published column is generated by the assembler, never read from the
# episode; the capture's own episode numbering starts at 0.
EPISODE_ID = 0


def make_ride():
    """The settled t=0 physical sim ``make_python_ride`` builds."""
    from bike_sim.cli import ride
    args = ride.parse_args([
        '--physics-config', str(PHYSICS), '--track', str(TRACK),
        '--headless', '--duration', '1', '--no-plots'])
    return ride.build_physical_simulation_from_args(args)


def force_oracle_path():
    """``compile_plan`` -> None: every spec stays on the Python encoder.

    ``NativePhysicalSource.tables`` binds the symbol lazily inside the
    generator, so replacing the module attribute before iteration keeps
    ``encode_rows``/``arrow_batch`` — the reviewed oracle — on every table.
    """
    from bike_sim.recording import native_encode
    native_encode.compile_plan = lambda spec, all_roots=None: None


def record_batch(spec, batch, episode_id, pa):
    """The RecordBatch ``storage._write_batch`` builds for one batch."""
    from bike_sim.recording.contracts import PieceBatch
    from bike_sim.recording.native_encode import pieces_to_arrow
    from bike_sim.recording.schema import arrow_batch
    if isinstance(batch, PieceBatch):
        return pieces_to_arrow(spec, batch.row_count, batch.pieces,
                               episode_id, pa)
    return arrow_batch(spec, batch, episode_id, pa)


def insert_record(connection, table, record, pa):
    """``storage._write_batch``'s DuckDB leg, unchanged."""
    from bike_sim.recording.schema import quote
    name = '_owned_recording_batch'
    connection.register(name, pa.Table.from_batches([record]))
    try:
        columns = ', '.join(quote(column) for column in record.schema.names)
        connection.execute(
            f'INSERT INTO {quote(table)} ({columns}) '
            f'SELECT {columns} FROM {quote(name)}')
    finally:
        connection.unregister(name)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description='Time the encode/Arrow/DuckDB stages of recording '
                    'publication on a sealed native episode.')
    parser.add_argument('--steps', type=int, default=5000,
                        help='advance this many accounted intervals before sealing')
    parser.add_argument('--batch-rows', type=int, default=4096,
                        help='source.tables/insert batch bound (publication default 4096)')
    parser.add_argument('--record-decimation', type=int, default=80,
                        help='energy/momentum measurement cadence')
    parser.add_argument('--oracle', action='store_true',
                        help='pin compile_plan to None: the reviewed Python encode path')
    args = parser.parse_args(argv)
    if args.steps < 1 or args.batch_rows < 1 or args.record_decimation < 1:
        parser.error('--steps, --batch-rows and --record-decimation must be positive')
    if args.oracle:
        force_oracle_path()

    from bike_sim.native.runtime import create_native_ride
    from bike_sim.recording.catalog import build_catalog
    from bike_sim.recording.native import NativePhysicalSource, model_joints
    from bike_sim.recording.schema import all_tables, create_streams

    sim = make_ride()
    # Non-strict (diagnostic) monitor: a violation marks the evidence but
    # must not truncate the measured episode.
    driver = create_native_ride(sim, strict=False,
                                record_decimation=args.record_decimation,
                                retention='full')
    try:
        tick = time.perf_counter()
        advance = driver.advance(args.steps)
        advance_s = time.perf_counter() - tick
        episode = driver.seal_episode()
        catalog = build_catalog(model_joints(driver.make_render_model()))
    finally:
        driver.close()

    source = NativePhysicalSource(episode, catalog, ordinary_commands=True)
    specs = {spec.name: spec for spec in all_tables()}

    tick = time.perf_counter()
    batches, encode_seconds = [], {}
    stream = source.tables(batch_rows=args.batch_rows)
    while True:
        inner = time.perf_counter()
        try:
            batch = next(stream)
        except StopIteration:
            break
        encode_seconds[batch.table] = \
            encode_seconds.get(batch.table, 0.) + time.perf_counter() - inner
        batches.append(batch)
    encode_s = time.perf_counter() - tick

    import pyarrow as pa
    records = []
    tick = time.perf_counter()
    for batch in batches:
        if not batch.row_count:
            continue
        records.append((batch.table,
                        record_batch(specs[batch.table], batch, EPISODE_ID, pa)))
    arrow_s = time.perf_counter() - tick

    import duckdb
    out_dir = Path(tempfile.mkdtemp(prefix='recording_finalize_bench_'))
    database = out_dir/'run.duckdb'
    connection = duckdb.connect(str(database), config={
        'autoload_known_extensions': 'false',
        'autoinstall_known_extensions': 'false'})
    try:
        tick = time.perf_counter()
        connection.execute('BEGIN TRANSACTION')
        create_streams(connection)
        for table, record in records:
            insert_record(connection, table, record, pa)
        connection.execute('COMMIT')
        connection.execute('CHECKPOINT')
        duckdb_s = time.perf_counter() - tick
    finally:
        connection.close()

    from bike_sim.recording.contracts import PieceBatch
    mode = 'oracle' if args.oracle else 'native'
    rows, kinds = {}, {'PieceBatch': 0, 'TableBatch': 0}
    for batch in batches:
        rows[batch.table] = rows.get(batch.table, 0) + batch.row_count
        kinds['PieceBatch' if isinstance(batch, PieceBatch)
              else 'TableBatch'] += 1
    print(f'mode={mode} steps={args.steps} sealed_rows={episode.row_count} '
          f'advance={advance_s:.2f}s advance_reason={advance.reason}')
    print(f'batches: PieceBatch={kinds["PieceBatch"]} '
          f'TableBatch={kinds["TableBatch"]} '
          f'(oracle mode must emit only TableBatch)')
    for name in sorted(rows):
        print(f'  {name:<28} rows={rows[name]:>8} '
              f'encode={encode_seconds.get(name, 0.):.3f}s')
    print(f'stages: encode={encode_s:.3f}s arrow={arrow_s:.3f}s '
          f'duckdb={duckdb_s:.3f}s '
          f'total={encode_s + arrow_s + duckdb_s:.3f}s db={database}')
    # Platform/provider provenance is part of the report: a native-vs-oracle
    # number without the recorded platform, numerical provider and extension
    # identity is not comparable evidence. A provenance failure is reported,
    # never hidden behind a timing line.
    try:
        from bike_sim.native.artifact import execution_provenance
        provenance = execution_provenance('native')
    except Exception as error:
        provenance = {'error': f'{type(error).__name__}: {error}'}
    print('provenance: ' + json.dumps(provenance, sort_keys=True))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
