def test_reads_and_invalid_push_do_not_consume_rng(raw_sensor):
    config = replace(SensorConfig(), latency_s=0.)
    a, b = SensorPipeline(config, seed=23), SensorPipeline(config, seed=23)
    a.reset(raw_sensor())
    b.reset(raw_sensor())
    assert a.read(0.) == a.read(0.)
    with pytest.raises(ValueError):
        a.push(raw_sensor())
    a.push(raw_sensor(.01))
    b.push(raw_sensor(.01))
    assert a.read(.01) == b.read(.01)


def test_pipeline_matches_frozen_pre_refactor_sensor_trace(raw_sensor, assert_tree):
    # The old pipeline is retained verbatim; expected draws/queue behavior do
    # not call the refactored helper. No golden values were generated by a run
    # during this source-only delivery.
    from dataclasses import asdict
    import _legacy_sensor_oracle as legacy
    config = replace(SensorConfig(), latency_s=.007, maximum_age_s=.012,
        acceleration_bias_mps2=(.1, -.2, .3), gyro_bias_rad_s=.004,
        dropout_probability=.35, imu_enabled=False)
    reference = legacy.SensorPipeline(legacy.SensorConfig(**asdict(config)), seed=210)
    actual = SensorPipeline(config, seed=210)
    reference.reset(legacy.SensorObservation(**asdict(raw_sensor())))
    actual.reset(raw_sensor())
    for index in range(20):
        time_s = index*.005
        if index:
            reference.push(legacy.SensorObservation(**asdict(raw_sensor(time_s))))
            actual.push(raw_sensor(time_s))
        for now in (time_s, time_s+.001, time_s+.001):
            assert_tree(asdict(actual.read(now)), asdict(reference.read(now)), atol=0., rtol=0.)
    assert actual.samples_attempted == reference.samples_attempted
    assert actual.samples_dropped == reference.samples_dropped
